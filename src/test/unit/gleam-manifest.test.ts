import { describe, expect, it } from 'vitest';
import { dependencyAtOffset, manifestAdapterForPath } from '../../core/manifest';
import { extractGleamDependencies, gleamPinnedVersion } from '../../core/gleam-manifest';
import { gleamLockfileFor, isGleamLockfilePath, parseGleamLockfile } from '../../core/gleam-lockfile';

describe('Gleam dependencies', () => {
  const manifest = String.raw`name = "example"
version = "1.0.0"

[dependencies]
gleam_stdlib = ">= 0.44.0 and < 2.0.0"
gleam_http = { hex = "gleam_http", version = "~> 4.0" }
local_package = { path = "../local_package" }
git_package = {
  git = "https://example.test/git_package.git",
  ref = "0123456789abcdef"
}
"quoted.package" = "~> 1.0"

[dev_dependencies]
gleeunit = ">= 1.0.0 and < 2.0.0"

[javascript]
typescript_declarations = true`;

  it('matches gleam.toml but not the lock file', () => {
    expect(manifestAdapterForPath('/repo/gleam.toml')?.kind).toBe('gleam');
    expect(manifestAdapterForPath('/repo/manifest.toml')).toBeUndefined();
  });

  it('extracts version, Hex, path, Git and development dependencies', () => {
    expect(extractGleamDependencies(manifest).map((dependency) => `${dependency.scope}:${dependency.noteKey}`))
      .toEqual([
        'dependencies:gleam_stdlib',
        'dependencies:gleam_http',
        'dependencies:local_package',
        'dependencies:git_package',
        'dependencies:quoted.package',
        'dev_dependencies:gleeunit',
      ]);
  });

  it('reads the older [dev-dependencies] table as the same development scope', () => {
    const text = `[dependencies]\ngleam_stdlib = "~> 0.40"\n\n[dev-dependencies]\ngleeunit = "~> 1.0"\n\n[dev_dependencies]\ngleeunit = "~> 1.0"\n`;
    expect(extractGleamDependencies(text).map((dependency) => `${dependency.scope}:${dependency.noteKey}`))
      .toEqual(['dependencies:gleam_stdlib', 'dev_dependencies:gleeunit']);
  });

  it('keeps dependency keys clickable and uses them as marker anchors', () => {
    const dependencies = extractGleamDependencies(manifest);
    const stdlib = dependencies[0]!;
    expect(manifest.slice(stdlib.primaryRange.offset, stdlib.primaryRange.offset + stdlib.primaryRange.length))
      .toBe('gleam_stdlib');
    expect(stdlib.iconRange).toEqual(stdlib.primaryRange);
    expect(dependencyAtOffset(dependencies, stdlib.primaryRange.offset + 2)?.noteKey).toBe('gleam_stdlib');

    const quoted = dependencies.find((dependency) => dependency.noteKey === 'quoted.package')!;
    expect(manifest.slice(quoted.primaryRange.offset, quoted.primaryRange.offset + quoted.primaryRange.length))
      .toBe('"quoted.package"');
  });

  it('ignores comments, unrelated tables and assignment-like text in values', () => {
    const text = String.raw`# [dependencies]
# commented = "1"
description = "fake = dependency"

[repository]
type = "github"
repo = "not_a_dependency"

[dependencies]
real_package = { git = "https://example.test/fake = value.git" }

[erlang]
application_start_module = "ignored"`;
    expect(extractGleamDependencies(text).map((dependency) => dependency.noteKey)).toEqual(['real_package']);
  });

  it('deduplicates within a scope and keeps safely parsed entries before a malformed tail', () => {
    const text = `[dependencies]\nfirst = "1"\nfirst = "2"\nbroken = {\n`;
    expect(extractGleamDependencies(text).map((dependency) => dependency.noteKey)).toEqual(['first', 'broken']);
  });

  it('keeps the requirement each dependency writes, and where it comes from when not hex.pm', () => {
    expect(Object.fromEntries(extractGleamDependencies(manifest).map((dependency) => [dependency.noteKey, dependency.versionSpec]))).toEqual({
      'gleam_stdlib': '>= 0.44.0 and < 2.0.0',
      // `hex` naming the package itself is no rename.
      'gleam_http': '~> 4.0',
      'local_package': 'file:../local_package',
      'git_package': 'git+https://example.test/git_package.git',
      'quoted.package': '~> 1.0',
      'gleeunit': '>= 1.0.0 and < 2.0.0',
    });
    const renamed = extractGleamDependencies('[dependencies]\nhttp = { hex = "gleam_http", version = "~> 4.0" }\nreq = { hex = "~> 2.0" }\n');
    expect(renamed.map((dependency) => dependency.versionSpec)).toEqual(['package:gleam_http', '~> 2.0']);
  });
});

describe('gleamPinnedVersion', () => {
  it('names the release of an exact requirement, with or without ==', () => {
    expect(gleamPinnedVersion('1.2.3')).toBe('1.2.3');
    expect(gleamPinnedVersion('== 0.44.0')).toBe('0.44.0');
    for (const spec of ['>= 0.44.0 and < 2.0.0', '~> 4.0', 'file:../x', undefined]) {
      expect(gleamPinnedVersion(spec), String(spec)).toBeUndefined();
    }
  });
});

describe('manifest.toml', () => {
  const lock = [
    '# This file was generated by Gleam',
    '',
    'packages = [',
    '  { name = "gleam_stdlib", version = "0.44.0", build_tools = ["gleam"], requirements = [], otp_app = "gleam_stdlib", source = "hex", outer_checksum = "A6" },',
    '  { name = "git_package", version = "1.0.0", build_tools = ["gleam"], requirements = [], source = "git", repo = "https://example.test/git_package.git", commit = "0123" },',
    '  { name = "local_package", version = "0.1.0", build_tools = ["gleam"], requirements = [], source = "local", path = "../local_package" },',
    ']',
    '',
    '[requirements]',
    'gleam_stdlib = { version = ">= 0.44.0 and < 2.0.0" }',
  ].join('\n');
  const parsed = parseGleamLockfile('manifest.toml', lock);

  it('gives a hex.pm package its locked version, and none to a git or local one', () => {
    expect(parsed.resolve('gleam.toml', 'gleam_stdlib', '>= 0.44.0 and < 2.0.0')).toBe('0.44.0');
    expect(parsed.resolve('gleam.toml', 'git_package', undefined)).toBeUndefined();
    expect(parsed.resolve('gleam.toml', 'local_package', 'file:../local_package')).toBeUndefined();
  });

  it('finds the manifest beside gleam.toml, and refuses another TOML file', () => {
    expect(isGleamLockfilePath('app/manifest.toml')).toBe(true);
    expect(gleamLockfileFor('app/gleam.toml', new Set(['app/manifest.toml']))).toBe('app/manifest.toml');
    expect(() => parseGleamLockfile('manifest.toml', '[package]\nname = "x"\n')).toThrow();
  });
});
